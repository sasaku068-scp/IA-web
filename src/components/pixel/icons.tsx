export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({ name }: { name: PixelIconName }) {
  const rows = ICONS[name];
  const cells: { x: number; y: number }[] = [];
  rows.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === "#") cells.push({ x, y });
    });
  });
  return (
    <svg width="16" height="16" viewBox="0 0 16 16" aria-hidden="true" shapeRendering="crispEdges" className="shrink-0">
      {cells.map((cell) => (
        <rect key={`${cell.x}-${cell.y}`} x={cell.x * 2} y={cell.y * 2} width="2" height="2" fill="currentColor" />
      ))}
    </svg>
  );
}
